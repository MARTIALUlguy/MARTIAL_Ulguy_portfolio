// Vérification que toutes les clés existent dans les deux langues
export const verifyI18n = () => {
  const frKeys = new Set(Object.keys(i18n.fr));
  const enKeys = new Set(Object.keys(i18n.en));
  const missingInEn = [...frKeys].filter(k => !enKeys.has(k));
  const missingInFr = [...enKeys].filter(k => !frKeys.has(k));
  return { missingInEn, missingInFr };
};
